  def ui_icon(name, css_class: "h-4 w-4")
    outline_icon(UI_ICONS.fetch(name.to_sym), css_class: css_class, stroke_width: "1.75")
  end

  # Item de menu com ícone à esquerda; o rótulo vem do bloco, porque alguns
  # itens levam um contador ao lado do texto. O ícone é decorativo: quem usa
  # leitor de tela ouve só o rótulo, que é o que importa.
  #
  # Todo item do menu leva ícone, inclusive os de idioma: um item sem ícone no
  # meio dos outros nasce recuado a menos e quebra a coluna do texto.
  def dropdown_link(path, icon:, **options, &content)
    link_to path, class: dropdown_classes(options), **options do
      dropdown_content(icon, &content)
    end
  end

  # A mesma linha para o que sai por POST/DELETE — sair da conta é o caso.
  def dropdown_button(path, icon:, **options, &content)
    button_to path, class: "#{dropdown_classes(options)} cursor-pointer", **options do
      dropdown_content(icon, &content)
    end
  end

  private
    def dropdown_classes(options)
      [ dropdown_item_class, options.delete(:class) ].compact.join(" ")
    end

    def dropdown_content(icon, &content)
      safe_join([ ui_icon(icon, css_class: "h-4 w-4 shrink-0 text-stone-400"), capture(&content) ])
    end
end
