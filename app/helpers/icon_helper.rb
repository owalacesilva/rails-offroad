  def ui_icon(name, css_class: "h-4 w-4")
    outline_icon(UI_ICONS.fetch(name.to_sym), css_class: css_class, stroke_width: "1.75")
  end

  # Item de menu com ícone à esquerda; o rótulo vem do bloco, porque alguns
  # itens levam um contador ao lado do texto. O ícone é decorativo: quem usa
  # leitor de tela ouve só o rótulo, que é o que importa.
  #
  # Todo item do menu leva ícone, inclusive os de idioma: um item sem ícone no
  # meio dos outros nasce recuado a menos e quebra a coluna do texto.
  # `tone:` viaja dentro de options, e não como parâmetro próprio, para os dois
  # construtores continuarem com três parâmetros. Escolhe a cor do item:
  # :danger para o que não tem volta, :positive para aprovar. Ver
  # ApplicationHelper::DROPDOWN_TONES.
  def dropdown_link(path, icon:, **options, &content)
    tone = options.delete(:tone) { :default }

    link_to path, class: dropdown_classes(options, tone), **options do
      dropdown_content(icon, tone, &content)
    end
  end

  # A mesma linha para o que sai por POST/PATCH/DELETE — sair da conta e as
  # ações das tabelas da moderação são o caso.
  def dropdown_button(path, icon:, **options, &content)
    tone = options.delete(:tone) { :default }

    button_to path, class: "#{dropdown_classes(options, tone)} cursor-pointer", **options do
      dropdown_content(icon, tone, &content)
    end
  end

  private
    def dropdown_classes(options, tone)
      [ dropdown_item_class(tone: tone), options.delete(:class) ].compact.join(" ")
    end

    def dropdown_content(icon, tone, &content)
      safe_join([ ui_icon(icon, css_class: dropdown_icon_class(tone: tone)), capture(&content) ])
    end
end
